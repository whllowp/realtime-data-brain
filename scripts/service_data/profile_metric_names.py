"""What do the Prometheus metric files actually contain, and over what span?

`api_responses` turned out to be unusable — 150 requests per case over 58 s, all 4xx because the workload
is generated by a fuzzer — so the only possible source of service-side golden signals is `metric_data`.
This scans every case's CSVs and reports:

  * the set of Prometheus metric names (`__name__`), because the catalogue needs request counts, error
    counts or latency histograms, and container CPU is not a service-level signal;
  * the time span and sampling interval per case, because 58 seconds is too short to window;
  * which metrics exist in every case (joinable) versus only some.

If no request/latency metric exists, the honest conclusion is that this dataset cannot test the
service-side half of the architecture, and that finding should be recorded rather than worked around by
substituting CPU for QPS and calling it a service test.
"""
from __future__ import annotations

import csv
from collections import Counter
from pathlib import Path
from typing import Dict, List, Set

REPO_ROOT = Path(__file__).resolve().parents[2]
DATA = REPO_ROOT / "data" / "anomod" / "SN_data" / "metric_data"

#: Names that would count as a service-level golden signal rather than an infrastructure metric.
SERVICE_HINTS = ("http", "request", "latency", "duration", "response", "error", "span", "rpc", "endpoint")


def scan_case(path: Path) -> Dict[str, object]:
    names: Counter = Counter()
    spans: Dict[str, tuple] = {}
    for csv_path in sorted(path.glob("*.csv")):
        first = last = None
        try:
            with csv_path.open(encoding="utf-8", newline="") as handle:
                reader = csv.DictReader(handle)
                for row in reader:
                    stamp = row.get("timestamp")
                    if stamp:
                        if first is None:
                            first = stamp
                        last = stamp
                    name = row.get("__name__")
                    if name:
                        names[name] += 1
        except (OSError, UnicodeDecodeError, csv.Error):
            continue
        if first and last:
            spans[csv_path.name] = (first, last)
    return {"names": names, "spans": spans}


def main() -> int:
    if not DATA.is_dir():
        print("metric_data not found under %s" % DATA)
        return 2
    cases = sorted(p for p in DATA.iterdir() if p.is_dir())
    print("metric cases: %d" % len(cases))
    print("")

    all_names: Counter = Counter()
    per_case_names: List[Set[str]] = []
    sample_spans: Dict[str, tuple] = {}
    for case in cases:
        info = scan_case(case)
        names = info["names"]
        per_case_names.append(set(names))
        all_names.update(names)
        if not sample_spans:
            sample_spans = info["spans"]

    print("distinct __name__ values: %d" % len(all_names))
    print("")
    print("%-56s %10s %s" % ("__name__", "rows", "in all cases?"))
    print("-" * 80)
    for name, count in all_names.most_common(40):
        everywhere = all(name in s for s in per_case_names)
        print("%-56s %10d %s" % (name[:56], count, "yes" if everywhere else "no"))

    print("")
    service_like = [n for n in all_names if any(h in n.lower() for h in SERVICE_HINTS)]
    print("names that look service-level: %s" % (service_like or "NONE"))
    print("")
    print("time span of the first case, by file:")
    for file_name, (first, last) in sorted(sample_spans.items()):
        print("  %-46s %s .. %s" % (file_name[:46], first, last))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
